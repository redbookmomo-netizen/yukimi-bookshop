export function makeFillerBook(seed, color) {
  let s = (seed * 2654435761) >>> 0;
  const r = () => { s ^= s << 13; s >>>= 0; s ^= s >>> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
  const keys = Object.keys(POOLS);
  const pool = POOLS[keys[Math.floor(r() * keys.length)]];
  const vols = ['', '', '', '　上卷', '　下卷', '　第二卷', '　续编'];
  const title = pool.titles[Math.floor(r() * pool.titles.length)] + vols[Math.floor(r() * vols.length)];
  const author = pool.authors[Math.floor(r() * pool.authors.length)];
  const idx = pool.entries.map((_, i) => i).sort(() => r() - 0.5).slice(0, 3 + Math.floor(r() * 2));
  const pages = idx.map((i) => ({ type: 'entry', head: pool.entries[i][0], text: pool.entries[i][1] }));
  const found = r() < 0.5 ? FOUND[Math.floor(r() * FOUND.length)] : null;
  if (found) pages.splice(1 + Math.floor(r() * (pages.length - 1)), 0, { type: 'found', ...found });
  const year = 20 + Math.floor(r() * 40);
  const price = [100, 200, 300, 300, 500, 500, 800][Math.floor(r() * 7)];
  return {
    id: 'f' + seed, title, author, color, ink: '#e8d6a6', pages,
    filler: true, year, price,
  };
}
